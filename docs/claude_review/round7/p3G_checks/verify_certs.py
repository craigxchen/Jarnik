"""Independent verifier for the pinning closure of gtight.py (p3G.md Lemma 2.3, Theorem 3.1).

Independent of gtight.closure: it does not use the union-find.  For every certificate it
  1. recomputes A_v from the Gaussian primes with Python ints, D_s, and checks tightness by
     L_X % |D| == 0 with L_X = odd lcm (q^(A_q), q <= X odd, q not dividing N), |D| odd;
  2. recomputes the orientation sigma from an mpmath (60 digits) value of arg A_v and checks
     it against the stored one; recomputes S = sin^2 d exactly and checks the arc condition
     (S > 1/2 for 'self', S + S' > 1 for 'pair');
  3. checks that the circuit vector (2 sigma v, or sigma v + sigma' v') lies in the lattice
     generated by the vectors pinned so far (incremental Hermite normal form over Z);
  4. adds v_e to the lattice.
At the end it reports, for every column k, whether e_k or 2 e_k lies in the lattice.
"""
import sys
from fractions import Fraction
import mpmath as mp
from gtight import lcm_odd_part

mp.mp.dps = 60


def gmul(x, y):
    return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])


def gconj(x):
    return (x[0], -x[1])


def monomial(gp, vec):
    A = (1, 0)
    for k, c in vec.items():
        base = gp[k] if c > 0 else gconj(gp[k])
        for _ in range(abs(c)):
            A = gmul(A, base)
    return A


def Dval(A, s):
    X, Y = A
    return (Y, X - Y, X, X + Y)[s]


class ZLattice:
    """Incremental echelon form over Z for sparse integer vectors (dict col->int)."""

    def __init__(self, r):
        self.r = r
        self.rows = {}  # pivot column -> dict (pivot = smallest column with nonzero entry)

    @staticmethod
    def _lead(v):
        return min(v) if v else None

    @staticmethod
    def _axpy(v, q, row):
        """return v - q*row (dicts)."""
        w = dict(v)
        for k, x in row.items():
            y = w.get(k, 0) - q * x
            if y:
                w[k] = y
            else:
                w.pop(k, None)
        return w

    def contains(self, v):
        v = {k: x for k, x in v.items() if x}
        while v:
            col = self._lead(v)
            if col not in self.rows:
                return False
            row = self.rows[col]
            if v[col] % row[col] != 0:
                return False
            v = self._axpy(v, v[col] // row[col], row)
        return True

    def insert(self, v):
        v = {k: x for k, x in v.items() if x}
        while v:
            col = self._lead(v)
            if col not in self.rows:
                if v[col] < 0:
                    v = {k: -x for k, x in v.items()}
                self.rows[col] = v
                return
            row = self.rows[col]
            a, b = row[col], v[col]
            if b % a == 0:
                v = self._axpy(v, b // a, row)
                continue
            g, x, y = egcd(a, b)
            newrow = {}
            for k in set(row) | set(v):
                t = x * row.get(k, 0) + y * v.get(k, 0)
                if t:
                    newrow[k] = t
            newv = {}
            for k in set(row) | set(v):
                t = (b // g) * row.get(k, 0) - (a // g) * v.get(k, 0)
                if t:
                    newv[k] = t
            if newrow[col] < 0:
                newrow = {k: -t for k, t in newrow.items()}
            self.rows[col] = newrow
            v = newv


def egcd(a, b):
    if b == 0:
        return (abs(a), (1 if a >= 0 else -1), 0)
    x0, y0, x1, y1 = 1, 0, 0, 1
    aa, bb = a, b
    while bb != 0:
        q = aa // bb
        aa, bb = bb, aa - q * bb
        x0, x1 = x1, x0 - q * x1
        y0, y1 = y1, y0 - q * y1
    if aa < 0:
        aa, x0, y0 = -aa, -x0, -y0
    return aa, x0, y0


def dense(vec, r, scale=1):
    v = {}
    for k, c in vec.items():
        v[k] = v.get(k, 0) + scale * c
    return v


def check_relation(gp, rel, X, L):
    kind, i, j, tau, s, D, normA, sg = rel
    if kind == 'S':
        vec = {i: 1}
    elif kind == 'T':
        vec = {i: 2}
    elif kind == 'Q':
        (i0, j0, k0), (t1, t2) = i, j
        vec = {i0: 1, j0: t1, k0: t2}
    else:
        vec = {i: 1, j: tau}
    A = monomial(gp, vec)
    Dv = Dval(A, s)
    assert Dv == D, ('D mismatch', rel, Dv)
    assert A[0] ** 2 + A[1] ** 2 == normA
    assert Dv % 2 != 0 and L % abs(Dv) == 0, ('not tight', rel)
    ang = mp.atan2(A[1], A[0])
    alpha = mp.fmod(ang - s * mp.pi / 4, mp.pi)
    if alpha < 0:
        alpha += mp.pi
    sigma = 1 if alpha < mp.pi / 2 else -1
    assert sigma == sg, ('orientation mismatch', rel)
    nu2 = Fraction(1) if s % 2 == 0 else Fraction(1, 2)
    S = nu2 * Fraction(Dv * Dv, normA)
    d = min(alpha, mp.pi - alpha)
    assert abs(mp.sin(d) ** 2 - mp.mpf(S.numerator) / S.denominator) < mp.mpf(10) ** -40
    return vec, sigma, S


def verify(gp, X, rels, log, exclude=()):
    r = len(gp)
    L = lcm_odd_part(X, exclude)
    lat = ZLattice(r)
    for cert in log:
        if cert[0] == 'self':
            e = cert[1]
            vec, sg, S = check_relation(gp, rels[e], X, L)
            assert S > Fraction(1, 2), 'self arc'
            assert lat.contains(dense(vec, r, 2 * sg)), 'self circuit not in lattice'
            lat.insert(dense(vec, r))
        else:
            e, e2 = cert[1], cert[2]
            vec, sg, S = check_relation(gp, rels[e], X, L)
            vec2, sg2, S2 = check_relation(gp, rels[e2], X, L)
            assert S + S2 > 1, 'pair arc'
            circ = dense(vec, r, sg)
            for k, t in dense(vec2, r, sg2).items():
                circ[k] = circ.get(k, 0) + t
            assert lat.contains(circ), 'pair circuit not in lattice'
            lat.insert(dense(vec, r))
    exact = sum(lat.contains(dense({k: 1}, r)) for k in range(r))
    half = sum(lat.contains(dense({k: 2}, r)) for k in range(r))
    return exact, half


