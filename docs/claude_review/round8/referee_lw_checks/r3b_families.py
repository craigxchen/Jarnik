"""Referee check R3b: positive-dimensional families of light characters of the skew double core.

A set Z of types with rank(Z u {1}) <= M-2 has a kernel N of dimension >= 2 in the zero-sum space;
the generic c in N vanishes exactly on the types lying in span(Z u {1}).  So infinitely many primitive
characters share the support size s_gen = #types - #(types in span(Z u {1})).  The census of
lw.md §5.2 counts only characters determined by their zero set; this script finds the smallest s_gen
over all spans generated by (M-2)-subsets (exact rank mod p = 2^31-1, confirmed over Q by Fraction
elimination for the minimisers).
Usage: python3 r3b_families.py
"""
import itertools
from fractions import Fraction
from r1_dcore import build
from r2_census import rank_modp

out = []
def log(s):
    print(s); out.append(s)

def rank_Q(rows):
    A = [[Fraction(x) for x in r] for r in rows]
    rk = 0
    for col in range(len(A[0])):
        piv = next((i for i in range(rk, len(A)) if A[i][col] != 0), None)
        if piv is None: continue
        A[rk], A[piv] = A[piv], A[rk]
        for i in range(len(A)):
            if i != rk and A[i][col] != 0:
                f = A[i][col] / A[rk][col]
                A[i] = [x - f*y for x, y in zip(A[i], A[rk])]
        rk += 1
    return rk

for q in (7, 11):
    M = q + 1
    K, s1, s2 = build(q)
    types = s1 + s2
    n = len(types)
    ones = [1]*M
    best = None; seen = set(); fams = {}
    for Z in itertools.combinations(range(n), M - 2):
        rows = [types[j] for j in Z] + [ones]
        r = rank_modp(rows, M)
        if r >= M - 1:
            continue
        # degenerate: compute the closure (types in the span), exactly via ranks mod p
        clos = tuple(j for j in range(n) if j in Z or rank_modp(rows + [types[j]], M) == r)
        if clos in seen: continue
        seen.add(clos)
        sgen = n - len(clos)
        dimN = (M - 1) - r + 0   # kernel dim inside zero-sum space = M - r  (ones in rows) ... see below
        dimN = M - r
        fams[(sgen, dimN)] = fams.get((sgen, dimN), 0) + 1
        if best is None or sgen < best[0]:
            best = (sgen, clos, r)
    # confirm the minimiser over Q
    sgen, clos, r = best
    rq = rank_Q([types[j] for j in clos] + [ones])
    log(f"q={q} M={M}: distinct degenerate spans (from (M-2)-subsets): {len(seen)}; "
        f"(generic s, kernel dim) -> number of spans: {sorted(fams.items())}")
    log(f"   smallest generic support s_gen = {sgen} (rank of span over Q = {rq}, mod p = {r}); "
        f"census of lw.md counts only zero-set-determined characters, complete for s < {sgen}")
open('r3b_families_out.txt', 'w').write('\n'.join(out) + '\n')
