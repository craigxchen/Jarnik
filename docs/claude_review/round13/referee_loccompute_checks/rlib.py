# Independent referee library: exact/mod-p leading-form ideals of finite point sets.
import itertools, math
from flint import fmpz_mat, nmod_mat, fmpq_mat, fmpz, fmpq
P = 2147483629  # prime < 2^31

def monos(nv, D, cap=None):
    """exponent tuples of total degree exactly D; cap = max exponent (None = unbounded)"""
    out=[]
    def rec(i, rem, cur):
        if i==nv-1:
            if cap is None or rem<=cap: out.append(tuple(cur+[rem]))
            return
        top = rem if cap is None else min(rem,cap)
        for e in range(top,-1,-1):
            rec(i+1, rem-e, cur+[e])
    if nv==0: return [()] if D==0 else []
    rec(0,D,[])
    return out

def evalmono(pt, e):
    r=1
    for a,b in zip(pt,e):
        if b: r*=a**b
    return r

def J_exact(points, Dmax, cap=None):
    """Return dict D -> list of integer coefficient vectors (basis over Q) of J(points)_D (leading forms),
    for D<=Dmax, w.r.t. monos(nv,D,cap). cap=2 means reduce x^3->x (points must be in {-1,0,1}). Exact over Q."""
    nv=len(points[0])
    allm=[]; deg=[]
    for D in range(Dmax+1):
        ms=monos(nv,D,cap); allm+=ms; deg+=[D]*len(ms)
    # order columns highest degree first so that rref kernel gives leading forms: we compute kernel of E (pts x monos)
    # J_D = projection to degree-D part of {f in ker E_{<=D}}.  Do per D: ker of E_{<=D}, take top parts.
    res={}
    for D in range(Dmax+1):
        cols=[i for i in range(len(allm)) if deg[i]<=D]
        # put degree-D columns first
        top=[i for i in cols if deg[i]==D]; low=[i for i in cols if deg[i]<D]
        order=top+low
        M=fmpz_mat([[evalmono(p,allm[i]) for i in order] for p in points])
        # nullspace: columns of N
        N,nul=M.nullspace()
        vecs=[]
        for j in range(nul):
            v=[N[i,j] for i in range(len(order))]
            vecs.append(v[:len(top)])
        # rank of top parts
        if vecs:
            T=fmpz_mat(vecs)
            r=T.rank()
            # basis: rref
            Tq=fmpq_mat(T); R,rk=Tq.rref()
            basis=[]
            for i in range(rk):
                row=[R[i,j] for j in range(len(top))]
                den=1
                for x in row: den=den*x.q//math.gcd(den,int(x.q))
                basis.append([int(x*den) for x in row])
            res[D]=basis
        else: res[D]=[]
    return res

import sympy as sp
def pull_forms(basis, ms_small, U, ys):
    """basis: list of int vectors over monomials ms_small in t-vars; U: list of integer direction vectors (len = #t);
    ys: sympy symbols. returns sympy Poly list"""
    ts=[sum(int(c)*y for c,y in zip(u,ys)) for u in U]
    out=[]
    for v in basis:
        f=0
        for c,e in zip(v,ms_small):
            if c:
                term=int(c)
                for t,k in zip(ts,e):
                    if k: term=term*t**k
                f+=term
        f=sp.expand(f)
        if f!=0: out.append(sp.Poly(f,*ys))
    return out

def ideal_dim(gens, ys, D, cap=None):
    """dim of degree-D part of ideal generated by homogeneous Polys gens (in Q[ys] or Q[ys]/(y^{cap+1})), mod P"""
    nv=len(ys); ms=monos(nv,D,cap); idx={m:i for i,m in enumerate(ms)}
    rows=[]
    for g in gens:
        dg=g.total_degree()
        if dg>D: continue
        for mu in monos(nv,D-dg,None if cap is None else cap):
            row={}
            for e,c in g.terms():
                ee=tuple(a+b for a,b in zip(e,mu))
                if cap is not None and max(ee)>cap: continue
                row[idx[ee]]=(row.get(idx[ee],0)+int(c))
            if any(row.values()): rows.append(row)
    if not rows: return 0, ms, rows
    M=nmod_mat(len(rows),len(ms),[0]*(len(rows)*len(ms)),P)
    for i,r in enumerate(rows):
        for j,c in r.items(): M[i,j]=c%P
    return M.rank(), ms, rows
