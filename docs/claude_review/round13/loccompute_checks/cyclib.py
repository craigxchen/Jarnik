"""Isotypic (Z_q, coordinate shift x_l -> x_{l+1}) version of the locality computation, for models with d = q
coordinates and a shift-invariant box A (Paley-12: q = 11; Syl(16): Singer cycle, q = 15).

All work mod PR (= 1 mod 2310).  Soundness: as in loclib (every row is the reduction of an exact element of J(A)
or of the local ideal over Q; ranks of row subsets are lower bounds).

Conventions: monomials of degree i (1 <= i < q, so all shift orbits are free) are arranged as an array
mon[o, t] = sigma^t(rep_o).  Component s basis f_{o,s} = sum_t w^{-st} sigma^t rep_o.  For a full vector h,
its s-coordinates are c_o = sum_t w^{st} h[mon[o,t]].  Back: full[mon[o,t]] = c_o w^{-st}.
"""
import itertools, math, time
import numpy as np
from flint import nmod_mat
from loclib import Ring, PR


def root_of_unity(q, p=PR):
    for h in range(2, 1000):
        w = pow(h, (p - 1) // q, p)
        if all(pow(w, q // r, p) != 1 for r in range(2, q + 1) if q % r == 0 and _isprime(r)):
            return w
    raise ValueError


def _isprime(r):
    return r > 1 and all(r % s for s in range(2, int(r ** 0.5) + 1))


def matmul_mod(a, b, p=PR):
    """(a @ b) mod p for int64 arrays with entries in [0,p), p < 2^31; split a in 16-bit halves."""
    a = np.asarray(a, dtype=np.int64); b = np.asarray(b, dtype=np.int64)
    a1 = a >> 16; a0 = a & 0xFFFF
    k = a.shape[-1]
    assert k < 2 ** 16
    r1 = (a1 @ b) % p
    r0 = (a0 @ b) % p
    return ((r1 << 16) % p + r0) % p


class CycRing:
    def __init__(self, ring, q):
        self.ring = ring; self.q = q; d = ring.d
        assert d == q
        self.w = root_of_unity(q)
        self.orb = {}        # degree -> array (n_orb, q) of monomial indices (periodic for short orbits)
        self.osize = {}; self.oscale = {}
        for i in range(1, ring.maxdeg + 2):
            M = ring.mons[i]; pw = ring.pw
            if getattr(ring, 'pos', None) is not None:
                look = lambda c: ring.pos[c].astype(np.int64)
            else:
                dct = ring.idx[i]
                look = lambda c: np.array([dct[int(z)] for z in c], dtype=np.int64)
            sh = np.stack([look(np.roll(M, t, axis=1) @ pw) for t in range(q)], axis=1)   # (N_i, q)
            isrep = sh[:, 0] == sh.min(axis=1)
            assert (np.arange(len(M)) == sh[:, 0]).all()
            rows = sh[isrep]
            sizes = np.array([len(set(r.tolist())) for r in rows], dtype=np.int64)
            assert sizes.sum() == len(M)
            self.orb[i] = rows
            self.osize[i] = sizes
            # true coordinate = (sum over 15 shifts) * r/q
            self.oscale[i] = np.array([(int(r) * pow(q, PR - 2, PR)) % PR for r in sizes], dtype=np.int64)
        self.Wfwd = {}   # s -> vector w^{s t}
        self.Wbwd = {}
        for s in range(q):
            self.Wfwd[s] = np.array([pow(self.w, (s * t) % q, PR) for t in range(q)], dtype=np.int64)
            self.Wbwd[s] = np.array([pow(self.w, (-s * t) % q, PR) for t in range(q)], dtype=np.int64)

    def project(self, H, i):
        """H: (k, N_i) full vectors -> dict s -> (k, n_orb) coordinates."""
        O = self.orb[i]
        X = H[:, O]                    # (k, n_orb, q)
        k, no, q = X.shape
        Wm = np.stack([self.Wfwd[s] for s in range(q)], axis=1)   # (q, q_s)
        Y = matmul_mod(X.reshape(k * no, q), Wm)                  # (k*no, q_s)
        Y = Y.reshape(k, no, q)
        Y = (Y * self.oscale[i][None, :, None]) % PR
        return {s: Y[:, :, s] for s in range(q)}

    def unproject(self, C, s, i):
        """C: (k, n_orb) coords of component s -> (k, N_i) full."""
        O = self.orb[i]
        k = C.shape[0]
        full = np.zeros((k, self.ring.N[i]), dtype=np.int64)
        vals = (C[:, :, None] * self.Wbwd[s][None, None, :]) % PR   # (k, no, q)
        full[:, O.reshape(-1)] = vals.reshape(k, -1)   # periodic rows: consistent values (c=0 if comp absent)
        return full


def rref_rows(M):
    """M int64 (r, c) -> (basis rows int64 (rk, c), rk) via flint rref mod PR."""
    if M.shape[0] == 0:
        return M, 0
    Mt = nmod_mat(M.shape[0], M.shape[1], [int(z) for z in M.ravel()], PR)
    R, rk = Mt.rref()
    B = np.array([int(x) for x in R.entries()], dtype=np.int64).reshape(M.shape[0], M.shape[1])[:rk]
    return B, rk


def rank_rows(M):
    if M.shape[0] == 0:
        return 0
    Mt = nmod_mat(M.shape[0], M.shape[1], [int(z) for z in M.ravel()], PR)
    return Mt.rank()


def ideal_dims_cyc(cr, gens, maxdeg, verbose=False, mind=1):
    """gens: {i: (k_i, N_i) array of full generator vectors (orbit representatives suffice)}.
    Ideal assumed shift-invariant (generated by the shift orbits of gens).  Returns dims per degree (mod p).
    Uses: P_s(R_1 J_{i-1}) = span_{s'} P_s(x_0 J^{s'}_{i-1})."""
    ring = cr.ring; q = cr.q
    dims = [0] * (maxdeg + 1)
    basis = {}     # s -> coords array of current degree
    for i in range(mind, maxdeg + 1):
        t0 = time.time()
        rows = {s: [] for s in range(q)}
        if basis:
            for s1, B in basis.items():
                if B.shape[0] == 0:
                    continue
                full = cr.unproject(B, s1, i - 1)
                # multiply by x_0
                tab = ring.mul[i - 1][0]; ok = tab >= 0
                X = np.zeros((full.shape[0], ring.N[i]), dtype=np.int64)
                X[:, tab[ok]] = full[:, ok]
                P = cr.project(X, i)
                for s in range(q):
                    rows[s].append(P[s])
        g = gens.get(i)
        if g is not None and len(g):
            P = cr.project(np.asarray(g, dtype=np.int64) % PR, i)
            for s in range(q):
                rows[s].append(P[s])
        newb = {}
        tot = 0
        for s in range(q):
            if rows[s]:
                M = np.vstack(rows[s]) % PR
                B, rk = rref_rows(M)
            else:
                B = np.zeros((0, cr.orb[i].shape[0]), dtype=np.int64); rk = 0
            newb[s] = B; tot += rk
        basis = newb
        dims[i] = tot
        if verbose:
            print(f"    deg {i}: dim {tot}  per comp {[newb[s].shape[0] for s in range(q)]} [{time.time()-t0:.0f}s]", flush=True)
    return dims


def hilbert_cyc(cr, A, maxdeg, shift_pts):
    """H_A(i), i = 0..maxdeg, mod p via isotypic decomposition of the evaluation map.
    shift_pts(k) = sigma k on points (must match the monomial shift: (sigma k)_{l+1} = k_l)."""
    ring = cr.ring; q = cr.q
    Aset = {tuple(k) for k in A.tolist()}
    reps = []; rsize = []
    seen = set()
    for k in A.tolist():
        k = tuple(k)
        if k in seen:
            continue
        orb = [k]
        for t in range(1, q):
            orb.append(tuple(np.roll(orb[-1], 1)))
        so = set(orb); seen |= so
        reps.append(k); rsize.append(len(so))
    rsize = np.array(rsize)
    R = np.array(reps, dtype=np.int64)
    # evaluation of f_{o,s} at rep k: sum_t w^{-st} (sigma^t rep_o)(k)
    ranks_cum = {s: [] for s in range(q)}
    H = [1] + [0] * maxdeg        # degree 0: constant, comp 0 (fixed point / all)
    # monomial values: mono e at k = prod k^e (k in {-1,0,1})
    def monvals(M, Pts):
        vals = np.ones((len(M), len(Pts)), dtype=np.int64)
        for x in range(ring.d):
            e = M[:, x][:, None]; kx = Pts[:, x][None, :]
            vals *= np.where(e == 0, 1, np.where(e == 1, kx, kx * kx))
        return vals
    global percomp
    percomp = {}
    cum_rows = {s: [] for s in range(q)}
    prev = {s: 0 for s in range(q)}
    colsel = {s: np.array([pow(cr.w, (s * int(r)) % q, PR) == 1 for r in rsize]) for s in range(q)}
    cum_rows[0].append(np.ones((1, int(colsel[0].sum())), dtype=np.int64)); prev[0] = 1
    for i in range(1, maxdeg + 1):
        O = cr.orb[i]
        V = monvals(ring.mons[i], R) % PR      # (N_i, nreps)
        tot = 0
        for s in range(q):
            Rs = colsel[s]
            Y = np.zeros((O.shape[0], int(Rs.sum())), dtype=np.int64)
            Vs = V[:, Rs]
            for t in range(q):
                Y = (Y + Vs[O[:, t]] * cr.Wbwd[s][t]) % PR
            cum_rows[s].append(Y)
            M = np.vstack(cum_rows[s])
            rk = rank_rows(M)
            tot += rk - prev[s]; percomp.setdefault(i, []).append(rk - prev[s]); prev[s] = rk
        H[i] = tot
    return H
