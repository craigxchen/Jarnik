#!/usr/bin/env python3
"""Checks for L5.md section 5 (profiles without twins).

(1) Theorem 5.1(i): A mod n is onto iff gcd(Delta_M(A), n) = 1 -- brute force on small matrices and moduli,
    and |A (Z/n)^r| = prod_i n/gcd(d_i, n) (Smith form) -- brute force.
(2) Proposition 5.3: H = A (Z/n)^r contains d_M (Z/n)^M; an injective kappa' in H exists when
    n/gcd(d_M, n) >= M  (brute force on small cases, and the converse direction reported as data).
(3) Evidence: random 0/1 profiles (M = 8..16, r = 2M, 4M): how often Delta_M = 1, how often a twin pair of
    columns exists, and the size of A_S^(-1) (max row l1-norm) for a unimodular minor S found by search.
(4) Exact: invariant factors of 0/1 Hadamard cores (J + H)/2 (Sylvester 8, 16; Paley 12, 20, 24) and of the
    sharp.md Paley twin profile (q0 = 11, b = 3) -- the latter has Delta_M = 1.
Run: python3 check_nontwin.py (output check_nontwin_out.txt)
"""
import itertools, random, math
from sympy import Matrix, gcd
from sympy.matrices.normalforms import invariant_factors
random.seed(5)

def inv_factors(A):
    return [int(d) for d in invariant_factors(Matrix(A))]

def delta_M(A):
    """gcd of maximal minors = index of the column lattice of A in Z^M (rank M assumed): integer echelon form."""
    M = len(A); r = len(A[0])
    rows = [[A[x][j] for x in range(M)] for j in range(r)]  # lattice generated by columns
    piv = []
    for c in range(M):
        # gcd-reduce column c among remaining rows
        rest = [row for row in rows if any(row)]
        while True:
            nz = [row for row in rest if row[c] != 0]
            if len(nz) <= 1:
                break
            nz.sort(key=lambda row: abs(row[c]))
            p = nz[0]
            for row in nz[1:]:
                q = row[c] // p[c]
                for k in range(M):
                    row[k] -= q * p[k]
        nz = [row for row in rest if row[c] != 0]
        if not nz:
            return 0
        p = nz[0]
        piv.append(abs(p[c]))
        rows = [row for row in rest if row is not p]
    return math.prod(piv)

def image_size_bruteforce(A, n):
    M = len(A); r = len(A[0])
    img = set()
    for l in itertools.product(range(n), repeat=r):
        img.add(tuple(sum(A[x][j] * l[j] for j in range(r)) % n for x in range(M)))
    return img

def part1():
    out = []; ok = True; cnt = 0
    for trial in range(25):
        M = random.randint(2, 3); r = M + random.randint(0, 1)
        A = [[random.randint(0, 2) for _ in range(r)] for _ in range(M)]
        if Matrix(A).rank() < M:
            continue
        d = inv_factors(A)
        DeltaM = math.prod(d)
        if delta_M([row[:] for row in A]) != DeltaM:
            ok = False
        for n in [2, 3, 4, 6, 8, 9, 10, 12]:
            if n ** r > 30000:
                continue
            img = image_size_bruteforce(A, n)
            pred = math.prod(n // math.gcd(di, n) for di in d)
            onto = len(img) == n ** M
            if len(img) != pred or onto != (math.gcd(DeltaM, n) == 1):
                ok = False
            # Prop 5.3: d_M (Z/n)^M subset of image
            dM = d[-1]
            for u in itertools.product(range(n), repeat=M):
                if tuple((dM * ui) % n for ui in u) not in img:
                    ok = False; break
            # injective element of image exists iff ... ; check sufficient condition
            inj = any(len(set(v)) == M for v in img)
            if n // math.gcd(dM, n) >= M and not inj:
                ok = False
            cnt += 1
    out.append('part1: %d (A, n) instances; image size = prod n/gcd(d_i,n), onto <=> gcd(Delta_M,n)=1, '
               'd_M (Z/n)^M in image, injective element when n/gcd(d_M,n) >= M: ok=%s' % (cnt, ok))
    return out, ok

def has_twin(A):
    M = len(A); r = len(A[0])
    cols = [tuple(A[x][j] for x in range(M)) for j in range(r)]
    for j, k in itertools.combinations(range(r), 2):
        if sum(abs(a - b) for a, b in zip(cols[j], cols[k])) == 1:
            return True
    return False

def part3():
    out = []
    for M in [8, 12, 16]:
        for rr in [2, 4]:
            r = rr * M
            n1 = 0; ntw = 0; norms = []; tot = 0
            for trial in range(15):
                while True:
                    A = [[random.randint(0, 1) for _ in range(r)] for _ in range(M)]
                    if len(set(map(tuple, A))) == M and Matrix(A).rank() == M:
                        break
                tot += 1
                if delta_M(A) == 1:
                    n1 += 1
                if has_twin(A):
                    ntw += 1
                # search a unimodular minor
                best = None
                import numpy as np
                for _ in range(300):
                    S = random.sample(range(r), M)
                    As = np.array([[A[x][j] for j in S] for x in range(M)], dtype=float)
                    if abs(abs(np.linalg.det(As)) - 1) < 1e-6:
                        Ai = np.rint(np.linalg.inv(As)).astype(int)
                        Ai_l = Ai.tolist(); As_l = As.astype(int).tolist()
                        if all(sum(As_l[i][k] * Ai_l[k][j] for k in range(M)) == (1 if i == j else 0)
                               for i in range(M) for j in range(M)):
                            nrm = max(sum(abs(Ai_l[i][x]) for x in range(M)) for i in range(M))
                            best = nrm if best is None else min(best, nrm)
                if best is not None:
                    norms.append(int(best))
            out.append('random 0/1, M=%d r=%d: Delta_M=1 in %d/%d; twin pair present in %d/%d; '
                       'unimodular minor found in %d/%d, min over found minors of max row-l1 of A_S^-1: '
                       'median %s, max %s' % (M, r, n1, tot, ntw, tot, len(norms), tot,
                                              sorted(norms)[len(norms) // 2] if norms else '-',
                                              max(norms) if norms else '-'))
    return out

def sylvester(k):
    H = [[1]]
    for _ in range(k):
        H = [row + row for row in H] + [row + [-v for v in row] for row in H]
    return H

def paley(q0):
    def leg(a):
        a %= q0
        return 0 if a == 0 else (1 if pow(a, (q0 - 1) // 2, q0) == 1 else -1)
    rows = [[1] * (q0 + 1)]
    for x in range(q0):
        rows.append([1] + [-(leg(a - x) + (1 if a == x else 0)) for a in range(q0)])
    return rows

def part4():
    out = []
    for name, H in [('Sylvester 8', sylvester(3)), ('Sylvester 16', sylvester(4)),
                    ('Paley 12', paley(11)), ('Paley 20', paley(19)), ('Paley 24', paley(23))]:
        M = len(H)
        for i in range(M):
            for k in range(M):
                assert sum(H[i][c] * H[k][c] for c in range(M)) == (M if i == k else 0)
        A01 = [[(1 + v) // 2 for v in row] for row in H]
        d = inv_factors(A01)
        out.append('%s core (J+H)/2, M=%d: invariant factors %s' % (name, M, d))
    # sharp.md Paley twin profile, q0 = 11, b = 3
    q0, b = 11, 3
    Hp = paley(q0)
    M = q0 + 1
    rows = list(range(M))  # row 0 = inf, row 1+x = x
    cols = [(a, i) for a in range(q0) for i in range(b)]
    S = [[Hp[x][1 + a] for (a, i) in cols] for x in rows]
    ci = {c: k for k, c in enumerate(cols)}
    for x in rows:
        fc = (0, 2) if x == 0 else (x - 1, 0)
        S[x][ci[fc]] = -S[x][ci[fc]]
    A = [[(1 + v) // 2 for v in row] for row in S]
    out.append('sharp.md Paley twin profile q0=11, b=3 (M=12, r=33): Delta_M = %d, twin pair present: %s'
               % (delta_M(A), has_twin(A)))
    return out

if __name__ == '__main__':
    o1, ok = part1()
    res = o1 + part4() + part3()
    res.append('ALL OK' if ok else 'FAILURE in part1')
    txt = '\n'.join(res)
    print(txt)
    open(__file__.replace('.py', '_out.txt'), 'w').write(txt + '\n')
