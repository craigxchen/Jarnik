"""Saturation of the homogeneous cone ideal I = (G_j) by linear forms via Bayer's trick (exact, sympy grevlex):
for a homogeneous ideal and a linear form l made the LAST variable of a grevlex order, I : l^inf is generated by
the Groebner basis elements divided by their highest power of l.  We saturate successively by all x_j
(w_j = 1) and all x_i - x_j (w_i = w_j), i.e. remove every point of X lying in one of these hyperplanes,
and print the Hilbert function of what remains (residual part of X: points with all w_j != 1, w_i != w_j).
Extra linear forms (in x) may be given on the command line."""
import sys, json, itertools, time
import sympy as sp
fn = sys.argv[1]
C = json.load(open(fn)); d = C['d']
X = sp.symbols('x0:%d' % d)
Y = sp.symbols('y0:%d' % d)
gens = [sp.expand(sp.sympify(f)) for f in C['forms']]

def saturate(gens, lform):
    co = [sp.Poly(lform, *X).coeff_monomial(X[i]) for i in range(d)]
    j = max(i for i in range(d) if co[i] != 0)
    others = [i for i in range(d) if i != j]
    sub = {X[i]: Y[t] for t, i in enumerate(others)}
    sub[X[j]] = (Y[d - 1] - sum(co[i] * Y[t] for t, i in enumerate(others))) / co[j]
    G = [sp.expand(g.subs(sub, simultaneous=True)) for g in gens]
    GB = sp.groebner(G, *Y, order='grevlex')
    out = []
    for g in GB.exprs:
        p = sp.Poly(g, *Y)
        mins = min(mon[d - 1] for mon in p.monoms())
        out.append(sp.expand(sp.cancel(g / Y[d - 1] ** mins)))
    back = {Y[t]: X[i] for t, i in enumerate(others)}
    back[Y[d - 1]] = lform
    return [sp.expand(g.subs(back, simultaneous=True)) for g in out]

def hf(gens, maxD=12):
    GB = sp.groebner(gens, *X, order='grevlex')
    if any(sp.Poly(g, *X).is_ground and g != 0 for g in GB.exprs):
        return None, GB
    LM = [sp.Poly(g, *X).monoms(order='grevlex')[0] for g in GB.exprs]
    H = []
    for D in range(0, maxD + 1):
        cnt = 0
        for comb in itertools.combinations_with_replacement(range(d), D):
            mon = [0] * d
            for i in comb:
                mon[i] += 1
            if not any(all(mon[i] >= l[i] for i in range(d)) for l in LM):
                cnt += 1
        H.append(cnt)
    return H, GB

if __name__ == "__main__":
    lforms = [X[j] for j in range(d)] + [X[i] - X[j] for i, j in itertools.combinations(range(d), 2)]
    lforms += [sp.sympify(s) for s in sys.argv[2:]]
    t0 = time.time()
    unit = False
    for lf in lforms:
        gens = saturate(gens, lf)
        if any(g != 0 and sp.Poly(g, *X).is_ground for g in gens):
            print("after saturating by", lf, ": unit ideal (%.1fs)" % (time.time() - t0))
            unit = True
            break
    H, GB = (None, None) if unit else hf(gens)
    print("residual after saturation: Hilbert function", H, "(%.1fs)" % (time.time() - t0))
    if H is None:
        print("RESIDUAL IS EMPTY: every point of the cone lies on one of the hyperplanes x_j = 0, x_i = x_j (or extra ones)")
    else:
        json.dump([str(g) for g in GB.exprs], open(fn.replace("_cone.json", "_residual_gb.json"), "w"))
