"""Sharpened anticode criterion (Theorem 3.4 of rigtheory.md), round 14.  Usage: python3 anticode2.py K "ps" [qmax]
For each q0 in F_K^ex and each anticode shape D (l1-diameter <= K-1; balls and double balls), report:
  cover : c(D) = Z/n  (c = genuine level-1 label)
  gen   : Lambda_c is generated by Lambda_c ∩ (D - D)  (index of the generated lattice = n, exact HNF)
  aff   : number of v in (D - D) \\ Lambda_c (one per sign) affordable at q0 for some unit (same table as deform.py)
If cover and gen hold: every non-genuine label has an extra collision of norm <= K-1 inside D - D (proved);
if moreover aff = 0, q0 is one-modulus rigid (certificate)."""
import sys, math
from sympy import Matrix
from rlib14 import *
from forced import forced_set
from anticode_cert import shapes
def lattice_index(vecs, r):
    # index in Z^r of the lattice spanned by vecs (0 if not full rank), via integer HNF/Smith (sympy)
    if not vecs: return 0
    from sympy.matrices.normalforms import smith_normal_form
    A = Matrix(vecs)
    if A.rank() < r: return 0
    S = smith_normal_form(A)
    d = 1
    for i in range(r): d *= abs(S[i, i])
    return d
def main(K, ps, qmax=10 ** 9):
    r = len(ps); pis = gaussian_primes(ps)
    F = [q for q in forced_set(ps, K, 60000) if q <= qmax]
    shp = []
    for dd in range(1, K): shp = shapes(r, dd) + shp
    for q0 in F:
        m, L = genuine_labels(ps, q0); n = m // 4
        others = [q for q in F if q != q0]
        memo = {}
        def aff(v):
            if v in memo: return memo[v]
            z = Zv(pis, v); nz = z[0] ** 2 + z[1] ** 2; ok = False
            for s in range(4):
                D = Ds(z, s); pr = q0
                for q in others: pr *= q ** vq(D, q)
                if pr * pr <= nz * (2 if s % 2 else 1): ok = True; break
            memo[v] = ok; return ok
        line = None
        for name, D in shp:
            if len(D) < n: continue
            if len({sum(a * b for a, b in zip(v, L)) % n for v in D}) < n: continue
            diffs = {tuple(x - y for x, y in zip(a, b)) for a in D for b in D}
            diffs.discard(tuple([0] * r))
            diffs = {v for v in diffs if canon(v)}
            gl = [v for v in diffs if sum(a * b for a, b in zip(v, L)) % n == 0]
            idx = lattice_index(gl + [tuple(n if i == j else 0 for i in range(r)) for j in range(r)], r) if n > 1 else 1
            ext = [v for v in diffs if sum(a * b for a, b in zip(v, L)) % n != 0]
            na = sum(1 for v in ext if aff(v))
            cand = f"{name}(|D|={len(D)}) gen={'yes' if idx == n else 'no(index %d)' % idx} extras={len(ext)} affordable={na}"
            if idx == n and (line is None or 'gen=yes' not in line or na == 0): line = cand
            if line is None: line = cand
            if idx == n and na == 0: break
        print(f"K={K} q0={q0} n={n}: " + (line if line else "no covering anticode"), flush=True)
if __name__ == "__main__":
    main(int(sys.argv[1]), [int(x) for x in sys.argv[2].split(",")], int(sys.argv[3]) if len(sys.argv) > 3 else 10 ** 9)
