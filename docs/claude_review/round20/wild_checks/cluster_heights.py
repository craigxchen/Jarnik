# Evidence for wild.md Thm B / Prop C: actual clusters and full circles.
#  * Prop C(ii) family: u=(1,g,...,g^{n-1},g^K), g=A+i: rigorous bound ratio >= K/(K+n-1); exact values printed.
#  * full circles: all lattice points of x^2+y^2=N, N = product of r split primes: ratio h(z)/h(ell_z) and rank.
#  * actual clusters: best k-windows on given N (incl. the referee's 10-point cluster on 1176852625):
#    ratio h(z)/h(ell_z) vs the bound (W/2)/((3/4)W+log C), and multiplicative rank of the normalised points.
import math, sys
from itertools import combinations
from line_examples import heights, gpow, ggcd, gdiv

def lattice_points(N):
    pts = []
    x = 0
    while x*x <= N:
        y2 = N - x*x; y = math.isqrt(y2)
        if y*y == y2:
            for sx in (1, -1):
                for sy in (1, -1):
                    pts.append((sx*x, sy*y))
        x += 1
    pts = sorted(set(pts), key=lambda p: math.atan2(p[1], p[0]))
    return pts

def factor(n):
    f = {}; d = 2
    while d*d <= n:
        while n % d == 0: f[d] = f.get(d, 0) + 1; n //= d
        d += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f

def gaussian_prime_above(p):
    for x in range(1, math.isqrt(p)+1):
        y2 = p - x*x; y = math.isqrt(y2)
        if y*y == y2: return (x, y)

def gval(z, pi):  # valuation of Gaussian integer z at Gaussian prime pi
    v = 0
    while True:
        n = pi[0]**2 + pi[1]**2
        re = z[0]*pi[0] + z[1]*pi[1]; im = z[1]*pi[0] - z[0]*pi[1]
        if re % n or im % n: return v
        z = (re//n, im//n); v += 1

def mult_rank(pts):
    # rank of the group generated by the ratios z_x/z_1 = exponent rank of rows (v_pi(z_x) - v_pi(z_1)) over primes of N
    g = (0, 0)
    for p in pts: g = ggcd(g, p)
    pts = [gdiv(p, g) for p in pts]
    N = pts[0][0]**2 + pts[0][1]**2
    primes = [p for p in factor(N) if p % 4 == 1]
    rows = []
    for z in pts:
        rows.append([gval(z, gaussian_prime_above(p)) for p in primes])
    diffs = [[a - b for a, b in zip(r, rows[0])] for r in rows[1:]]
    from anomaly_ranks import rank
    return rank(diffs) if diffs else 0, len(primes), N

def hsum_min(pts):
    # min over anchors of sum_x h(z_x/z_a), h(P/conj P)=(1/2)log Norm(P) with z_x/z_a = P/conj(P) reduced:
    # h(z_x/z_a) = (1/2) * log( N / Norm gcd(z_x,z_a) )  (normalised points)
    g = (0, 0)
    for p in pts: g = ggcd(g, p)
    pts = [gdiv(p, g) for p in pts]
    N = pts[0][0]**2 + pts[0][1]**2
    best = None
    for a in range(len(pts)):
        s = 0.0
        for x in range(len(pts)):
            if x == a: continue
            gg = ggcd(pts[x], pts[a]); ng = gg[0]**2 + gg[1]**2
            s += 0.5*math.log(N/ng)
        best = s if best is None else min(best, s)
    return best

def best_window(pts, k, N):
    R = math.sqrt(N)
    best = None
    L = len(pts)
    ang = [math.atan2(y, x) for x, y in pts]
    for s in range(L):
        idx = [(s + t) % L for t in range(k)]
        span = (ang[idx[-1]] - ang[idx[0]]) % (2*math.pi)
        C = 2*R*math.sin(span/2) / math.sqrt(R)  # chord length / sqrt(R) (upper bound for arc const via chord)
        if best is None or C < best[0]: best = (C, idx)
    return best

