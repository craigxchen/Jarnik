def VK(r,K,kmin=1):
    out=[]
    for v in itertools.product(range(-K,K+1),repeat=r):
        s=sum(abs(t) for t in v)
        if kmin<=s<=K: out.append(v)
    return out
def ordp(x,q):
    x=abs(x); e=0
    while x%q==0: x//=q; e+=1
    return e
# arithmetic in Z[i]/Q
def mmul(x,y,Q): return ((x[0]*y[0]-x[1]*y[1])%Q, (x[0]*y[1]+x[1]*y[0])%Q)
def mpow(x,e,Q):
    r=(1,0); b=(x[0]%Q,x[1]%Q)
    while e:
        if e&1: r=mmul(r,b,Q)
        b=mmul(b,b,Q); e>>=1
    return r
def minv(x,Q):
    nrm=(x[0]*x[0]+x[1]*x[1])%Q
    ni=pow(nrm,-1,Q)
    return ((x[0]*ni)%Q, (-x[1]*ni)%Q)
def factor(n):
    f=[];d=2
    while d*d<=n:
        if n%d==0:
            f.append(d)
            while n%d==0: n//=d
        d+=1
    if n>1: f.append(n)
    return f
def labels(pis,q,a=1,seed=1):
    """genuine labels L_j = dlog(pi_j/conj pi_j) in T_{q^a}, generator g with g^(m/4)=i. returns (m, L)."""
    Q=q**a
    m=(q-1 if q%4==1 else q+1)*q**(a-1)
    rng=random.Random(seed)
    pf=factor(m)
    while True:
        z=(rng.randrange(Q),rng.randrange(Q))
        if (z[0]*z[0]+z[1]*z[1])%q==0: continue
        g=mmul(z,minv(gconj(z),Q),Q)
        if all(mpow(g,m//l,Q)!=(1,0) for l in pf): break
    gi=mpow(g,m//4,Q)
    if gi==(0,1%Q): pass
    elif gi==(0,(Q-1)): g=minv(g,Q)
    else: raise RuntimeError('order-4 elt not +-i')
    assert mpow(g,m//4,Q)==(0,1)
    # dlog table
    tab={}; x=(1,0)
    for k in range(m):
        tab[x]=k; x=mmul(x,g,Q)
    L=[]
    for pi in pis:
        u=mmul(pi,minv(gconj(pi),Q),Q)
        L.append(tab[u])
    return m,L
