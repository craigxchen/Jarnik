def classcodes(L,n):
    r=len(L); codes=set()
    from math import gcd
    for u in range(1,n+1):
        if gcd(u,n)!=1: continue
        for eps in itertools.product((1,-1),repeat=r):
            code=0
            for j in range(r): code=code*n+((u*eps[j]*L[j])%n)
            codes.add(code)
    return sorted(codes)
def VKfast(r,K,kmin=1):
    """all v in Z^r with kmin<=||v||_1<=K, generated by support (efficient for large r)."""
    out=[]
    def comps(total,parts):
        if parts==1:
            yield (total,); return
        for a in range(1,total-parts+2):
            for rest in comps(total-a,parts-1): yield (a,)+rest
    for k in range(kmin,K+1):
        for sz in range(1,k+1):
            for supp in itertools.combinations(range(r),sz):
                for c in comps(k,sz):
                    for sg in itertools.product((1,-1),repeat=sz):
                        v=[0]*r
                        for j,a,s in zip(supp,c,sg): v[j]=a*s
                        out.append(tuple(v))
    return out
