"""Referee's own sampling of the ten-pair-cut angle model (Astra section 4)."""
import random, sys
from itertools import combinations, product
from mpmath import mp, mpf, pi, asin, exp, log, sin, cos, mpc, fabs
from sympy import Matrix, nextprime
mp.dps = 80
random.seed(int(sys.argv[1]) if len(sys.argv) > 1 else 3)
X = int(sys.argv[2]) if len(sys.argv) > 2 else 10**6
pairs = list(combinations(range(5), 2))
B0 = Matrix([[int(i in e) - int(4 in e) for e in pairs] for i in range(4)])
# ten primes = 1 mod 4 in [X,2X]
primes = []
p = X
while len(primes) < 10:
    p = nextprime(p)
    if p % 4 == 1 and random.random() < 0.3:
        primes.append(p)
assert primes[-1] <= 2*X
# right inverse: four columns with det +-1
for cols in combinations(range(10), 4):
    sub = B0[:, list(cols)]
    if abs(sub.det()) == 1:
        break
subinv = sub.inv()
ker = B0.nullspace()
# integral kernel basis via Smith-like: use sympy to get integer basis of ker_Z
from sympy.matrices.normalforms import hermite_normal_form
K = Matrix.hstack(*[k*k.applyfunc(lambda x: x.q).T.applyfunc(lambda x: x) [0] if False else k for k in ker])
# clear denominators of each kernel vector
import math
kb = []
for k in ker:
    den = 1
    for x in k:
        den = den*x.q//math.gcd(den, x.q)
    kb.append([int(x*den) for x in k])
# saturate: lattice generated by kb might be a sublattice of ker_Z; Haar on the subtorus is still obtained
# by uniform coefficients on a basis of ker_Z. Compute ker_Z basis: LLL-free approach via sympy smith not needed;
# we take kernel of the integer matrix via integer nullspace from column-style Hermite reduction.
Mk = Matrix(kb).T  # 10 x 6
# the index of span(kb) in ker_Z is gcd of 6x6 minors / content; we compensate by sampling u in [0,den) range
s = mpf(X)**-3
trials = int(sys.argv[3]) if len(sys.argv) > 3 else 20
fails_total = 0
for trial in range(trials):
    theta = [mpf(10*(j+1))*s + (mpf(random.random())-mpf(1)/2)*s for j in range(4)]
    phi0 = [mpf(0)]*10
    sol = subinv*Matrix(4, 1, [0, 0, 0, 0])
    vals = [sum(subinv[r, c]*theta[c] for c in range(4)) for r in range(4)]
    for r, c in enumerate(cols):
        phi0[c] = vals[r]
    # Haar on fibre: add sum u_k * 2pi * kb_k with u_k uniform in [0, 50) (sublattice-index safe)
    phi = list(phi0)
    for k in range(Mk.shape[1]):
        u = mpf(random.random())*50
        for r in range(10):
            phi[r] += 2*pi*u*Mk[r, k]
    phi = [x % (2*pi) for x in phi]
    # check B0 phi = theta mod 2pi
    for j in range(4):
        val = sum(B0[j, r]*phi[r] for r in range(10)) - theta[j]
        val = val - 2*pi*mp.nint(val/(2*pi))
        assert fabs(val) < mpf(10)**-60
    logp = [log(q) for q in primes]
    fails = 0
    checked = 0
    # all v with ||v||_1 <= 3, plus row-lattice v for c with small entries
    vs = set()
    for supp in range(1, 4):
        for idx in combinations(range(10), supp):
            for vals_ in product([-3, -2, -1, 1, 2, 3], repeat=supp):
                if sum(abs(x) for x in vals_) <= 3:
                    v = [0]*10
                    for i_, x in zip(idx, vals_):
                        v[i_] = x
                    vs.add(tuple(v))
    for c4 in product(range(-3, 4), repeat=4):
        c = list(c4) + [-sum(c4)]
        if any(c):
            vs.add(tuple(c[i]+c[j] for i, j in pairs))
    for v in vs:
        ang = sum(v[r]*phi[r] for r in range(10))
        w = sum(abs(v[r])*logp[r] for r in range(10))
        d1 = fabs(ang - (pi/2)*mp.nint(ang/(pi/2)))
        a2 = ang - pi/4
        d2 = fabs(a2 - (pi/2)*mp.nint(a2/(pi/2)))
        checked += 1
        if d1 < asin(exp(-w/2)) or d2 < asin(exp(-w/2)/mp.sqrt(2)):
            fails += 1
    fails_total += fails
    # points and diameter
    ang5 = [2*t for t in theta] + [mpf(0)]
    Delta = max(fabs(mp.expj(a)-mp.expj(b)) for a, b in combinations(ang5, 2))
    H = 1
    for q in primes:
        H *= q
    if trial == 0:
        print("X", X, "primes", primes)
        print("vectors checked per trial", checked)
    print("trial", trial, "gap failures", fails, " Delta/s =", mp.nstr(Delta/s, 6),
          " log Delta/log H =", mp.nstr(log(Delta)/log(H), 6))
print("total failures", fails_total)
