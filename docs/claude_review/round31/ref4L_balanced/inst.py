from sympy import factorint, isprime
from math import gcd, prod
from fractions import Fraction as F
from itertools import combinations
q=924; K=3999318414; P=15994547776559171401
ps=K*K+1
print("p*=P+329q:", ps==P+329*q, "p* prime:", isprime(ps), ps%4, "P prime:",isprime(P))
edges=list(combinations(range(1,6),2))
b=dict(zip(edges,[145,79,-31,109,85,-47,113,19,-41,25]))
cyc={(1,2),(2,3),(3,4),(4,5),(1,5)}
S={i:set(e for e in edges if (i in e)!=(e in cyc)) for i in range(1,6)}
J={e:P+q*b[e] for e in edges}
fac={}
for e in edges:
    fac[e]=factorint(J[e]); print(e,J[e],fac[e],"prime" if isprime(J[e]) else "")
allp=[p for e in edges for p in fac[e]]
print("squarefree:",all(v==1 for e in edges for v in fac[e].values()))
print("pairwise coprime:",len(allp)==len(set(allp)), all(gcd(J[e],J[f])==1 for e,f in combinations(edges,2)))
print("split:",all(p%4==1 for p in allp))
print("#prime blocks:",sum(isprime(J[e]) for e in edges))
N=prod(J.values())
R={1:4680,2:3861,3:2860,4:3168,5:2808}
d={1:-76,2:-55,3:-6,4:-34,5:-4}
f={1:F(26095),2:F(43223,2),3:F(16715),4:F(16813),5:F(16303)}
T={}
for i in R:
    t=P*P+d[i]*q*P+f[i]*q*q; assert t.denominator==1; T[i]=int(t)
print("gcd(T_i,R_i):",[gcd(T[i],R[i]) for i in R])
V={i:(K*T[i]-R[i],T[i]) for i in R}
print("primitive:",[gcd(*V[i]) for i in R])
n={i:prod(J[e] for e in S[i]) for i in R}
for (i,j) in edges:
    m=V[i][0]*V[j][1]-V[i][1]*V[j][0]
    g=prod(J[e] for e in S[i]&S[j])
    assert gcd(n[i],n[j])==g
    assert m%g==0
    print((i,j),"cofactor",m//g,"R_j-R_i",R[j]-R[i])
s=-K
for i in R:
    nv=V[i][0]**2+V[i][1]**2; dl=nv-n[i]
    form=(ps*T[i]**2-n[i])+2*s*T[i]*R[i]+F(s*s+1,ps)*R[i]**2
    print(i,"delta",dl,"formula ok",form==dl,"ineq",0<(1000*abs(dl))**5<n[i]**3,
          "ratio |d|/n^(3/5)",abs(dl)/n[i]**0.6, "|d|/P^2.5", abs(dl)/P**2.5,
          "parts", (ps*T[i]**2-n[i])/P**2.5, 2*s*T[i]*R[i]/P**2.5)
# index one: valuation matrix rank over primes: anchored lattice
import sympy
rows=[]
for e in edges:
    for p in fac[e]:
        rows.append([1 if e in S[i] else 0 for i in range(1,6)])
M=sympy.Matrix(rows)
# anchored: differences to mark 5? index of lattice generated by columns-> use Smith form on rows mod all-ones
A=sympy.Matrix([[r[i]-r[4] for i in range(4)] for r in rows])
from sympy.matrices.normalforms import smith_normal_form
print("SNF anchored:",smith_normal_form(A.T,domain=sympy.ZZ)[:,:4])
print("N bits",N.bit_length(),"P",P)
