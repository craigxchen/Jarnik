# Genuine label tuples omega_j = pi_j/conj(pi_j) mod l at inert l<=x; D(x), exact generator rank of subgroup,
# F_2 rank of Legendre vectors; check of the determinant bound for same-class pairs.
import sys, math
from sympy import primerange, isprime, factorint
from math import gcd

def gauss(p):
    a=1
    while True:
        b2=p-a*a
        b=math.isqrt(b2)
        if b*b==b2: 
            if a%2==0: a,b=b,a
            return (a,b)   # a odd, b even, both >0
        a+=1

def mul(x,y,l): return ((x[0]*y[0]-x[1]*y[1])%l,(x[0]*y[1]+x[1]*y[0])%l)
def pw(x,e,l):
    r=(1,0)
    while e:
        if e&1: r=mul(r,x,l)
        x=mul(x,x,l); e>>=1
    return r
def inv(x,l):
    n=(x[0]*x[0]+x[1]*x[1])%l
    ni=pow(n,-1,l); return ((x[0]*ni)%l,(-x[1]*ni)%l)

_dl={}
def dlog_table(l):
    if l in _dl: return _dl[l]
    n=l+1; fs=list(factorint(n))
    # find generator of mu_{l+1}: h^(l-1) for h in F_{l^2}^*
    for a in range(l):
        for b in range(1,l):
            g=pw((a,b),l-1,l)
            if all(pw(g,n//q,l)!=(1,0) for q in fs):
                tab={}; y=(1,0)
                for k in range(n): tab[y]=k; y=mul(y,g,l)
                _dl[l]=tab; return tab

def omega(pi,l):
    return dlog_table(l)[mul(pi,inv((pi[0],-pi[1]),l),l)]

def hnf_det(rows,n,d):
    # det of lattice spanned by rows (in Z^n) together with d Z^n; rows reduced mod d
    rows=[[v%d for v in r] for r in rows]+[[d if i==j else 0 for i in range(n)] for j in range(n)]
    det=1
    for c in range(n):
        piv=None
        rest=[]
        for r in rows:
            if r[c]==0: rest.append(r); continue
            if piv is None: piv=r; continue
            # gcd combine piv and r
            a,b=piv[c],r[c]
            g,x,y=egcd(a,b)
            newp=[(x*u+y*v) for u,v in zip(piv,r)]
            newr=[(b//g)*u-(a//g)*v for u,v in zip(piv,r)]
            piv=newp; rest.append([t%d for t in newr])
        det*=abs(piv[c])
        rows=[r for r in rest if any(r)]
    return det
def egcd(a,b):
    if b==0: return (a,1,0) if a>=0 else (-a,-1,0)
    g,x,y=egcd(b,a%b); return (g,y,x-(a//b)*y)

def group_rank(vecs,mods):
    # min number of generators of subgroup of prod Z/mods generated by vecs = max_r d_r
    primes=set()
    for m in mods: primes|=set(factorint(m))
    best=0; detail={}
    for r in sorted(primes):
        ex=[factorint(m).get(r,0) for m in mods]
        idx=[i for i,e in enumerate(ex) if e>0]
        n=len(idx); d=r**max(ex)
        # project to r-part: Z/m -> Z/r^e via multiplication? Z/m = Z/r^e x Z/m'; projection: v -> v mod r^e
        V=[[v[i]%(r**ex[i]) for i in idx] for v in vecs]
        # sublattice must include r^{e_i} e_i: add as rows
        diag=[[r**ex[i] if k==j else 0 for k in range(n)] for j,i in enumerate(idx)]
        detL=hnf_det(V+diag,n,d)
        detrL=hnf_det([[r*t for t in v] for v in V]+diag,n,d)
        # |H_r| = prod r^e / detL ; |rH_r| = prod r^e/detrL
        dr=round(math.log(detrL//detL,r)) if detrL//detL>1 else 0
        assert r**dr==detrL//detL
        detail[r]=dr; best=max(best,dr)
    return best,detail

def f2rank(vecs):
    basis=[]
    for v in vecs:
        x=v
        for b in basis: x=min(x,x^b)
        if x: basis.append(x)
    return len(basis)

def analyse(primes,xs,label):
    pis=[gauss(p) for p in primes]
    s=len(primes)
    print("==",label,"s=",s,"range",primes[0],primes[-1])
    for x in xs:
        ls=[l for l in primerange(3,x+1) if l%4==3]
        mods=[l+1 for l in ls]
        vecs=[tuple(omega(pi,l) for l in ls) for pi in pis]
        D=len(set(vecs))
        th=sum(math.log(l) for l in ls)
        # Legendre vectors (2-part sign): omega^{(l+1)/2}
        leg=[sum((1<<k) for k,l in enumerate(ls) if (v[k]*((l+1)//2))%(l+1)!=0) for v in vecs]
        # check sign = Legendre (p/l) = -1 iff bit set
        for p,lv in zip(primes,leg):
            for k,l in enumerate(ls):
                assert ((lv>>k)&1)==(1 if pow(p,(l-1)//2,l)==l-1 else 0)
        f2=f2rank(leg)
        rk,det=group_rank(vecs,mods) if s*len(ls)<=40000 else (None,None)
        # determinant check for same-class pairs
        cls={}
        for j,v in enumerate(vecs): cls.setdefault(v,[]).append(j)
        Q=1
        for l in ls: Q*=l
        viol=0;pairs=0
        for c in cls.values():
            for a in range(len(c)):
                for b in range(a+1,len(c)):
                    pa,pb=pis[c[a]],pis[c[b]]
                    im=pb[0]*pa[1]-pa[0]*pb[1]   # Im(pi_a conj pi_b)
                    pairs+=1
                    assert im%Q==0 and im!=0
                    if Q*Q>primes[c[a]]*primes[c[b]]: viol+=1
        nsing=sum(1 for c in cls.values() if len(c)==1)
        print(" x=%3d #l=%2d |G|=%.3g theta3=%.2f D=%d singletons=%d samepairs=%d viol=%d F2rank=%d rank=%s"%(
            x,len(ls),math.prod(mods),th,D,nsing,pairs,viol,f2,rk))
    return

if __name__=="__main__":
    for P in [100,500,1000,5000]:
        pr=[p for p in primerange(P,2*P+1) if p%4==1]
        analyse(pr,[3,7,11,19,23,31,43,47,59,67],"dyadic [%d,%d]"%(P,2*P))
    for s in [100,1000]:
        pr=[p for p in primerange(5,10**6) if p%4==1][:s]
        xs=[int(K*math.log(s)) for K in (1,2,3,4,6)]
        analyse(pr,xs,"first %d split primes, x=K log s, K=1,2,3,4,6"%s)
