# independent integer lattice index tools (no sympy)
from math import gcd
def lattice_index(vectors, dim):
    """index in Z^dim of the lattice spanned by given integer vectors (list of length-dim lists).
    returns 0 if rank < dim. Uses integer row reduction (HNF-like) on the generator list."""
    rows = [list(v) for v in vectors if any(v)]
    basis = []
    col = 0
    det = 1
    for col in range(dim):
        # among rows, eliminate column col by gcd steps
        piv = None
        rest = []
        for r in rows:
            if r[col] == 0:
                rest.append(r); continue
            if piv is None:
                piv = r; continue
            # euclid between piv and r on column col
            a, b = piv, r
            while b[col] != 0:
                qt = a[col] // b[col]
                a = [x - qt*y for x, y in zip(a, b)]
                a, b = b, a
            piv = a
            if any(b): rest.append(b)
        if piv is None:
            return 0
        det *= abs(piv[col])
        rows = [r for r in rest if any(r)]
    return det

def anchored_index(rowsvec, idx):
    """rowsvec[i] = exponent row (list over primes); idx = tuple of mark indices.
    index of lattice generated by prime columns of differences from first anchor."""
    a0 = rowsvec[idx[0]]
    k = len(idx) - 1
    ncol = len(a0)
    cols = [[rowsvec[i][p] - a0[p] for i in idx[1:]] for p in range(ncol)]
    return lattice_index(cols, k)
